import { expect, test, type Page } from '@playwright/test'
async function login(page: Page, username: string) {
 await page.goto('/security/operations')
 await page.getByRole('button', { name: 'Operator login' }).click()
 await page.getByLabel(/Operator account/).fill(username)
 await page.getByLabel('Operator password').fill('browser-test-operator-password')
 await page.getByRole('button', { name: 'Sign in as operator' }).click()
 await expect(page.getByRole('button', { name: 'Sign out' })).toBeVisible()
}

test('security operations, identities, audit integrity and emergency controls use real records and roles', async ({ page }) => {
 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
 await page.goto('/security/operations')
 await expect(page.getByText('Operator login required')).toBeVisible()
 expect((await page.request.get('/api/v1/security/status')).status()).toBe(401)
 expect((await page.request.post('/api/v1/security/emergency-stop', { data: { reason: 'unauthenticated attempt', confirm: true } })).status()).toBe(401)
 // Auditor: read-only views with backend-computed verification.
 await login(page, 'auditor_aki')
 const status = await (await page.request.get('/api/v1/security/status')).json()
 expect(status.protected_executions.simulated_emails_sent).toBeGreaterThanOrEqual(1)   // global count; earlier specs may add sends
 expect(status.authentication_failures).toBeGreaterThanOrEqual(1)
 await expect(page.getByText('Authentication failures')).toBeVisible()
 await expect(page.getByRole('button', { name: 'Activate emergency stop' })).toHaveCount(0)
 const ops = await (await page.request.get('/api/v1/security/operations')).json()
 const send = ops.find((o: { request_id: string }) => o.request_id === 'e2e_send')
 expect(send.state).toBe('SUCCEEDED')
 expect(ops.find((o: { request_id: string }) => o.request_id === 'e2e_send_unapproved').state).toBe('BLOCKED')
 await page.getByRole('link', { name: send.operation_id }).click()
 await expect(page.getByText('ALLOW · AUTHORIZED')).toBeVisible()
 await expect(page.getByText('SIMULATED_EMAIL_SENT', { exact: false }).first()).toBeVisible()
 await page.goto('/security/audit-integrity')
 await expect(page.getByText('Audit verification:')).toContainText('PASS')
 const report = await (await page.request.get('/api/v1/audit/verification')).json()
 await expect(page.getByText(String(report.chained_events), { exact: true }).first()).toBeVisible()
 await page.goto('/security/identities')
 await expect(page.getByRole('cell', { name: /runtime_alpha/ }).first()).toBeVisible()
 await expect(page.getByRole('button', { name: 'Revoke' })).toHaveCount(0)
 const headers = { 'X-CSRF-Token': (await (await page.request.get('/api/session')).json()).csrf_token }
 expect((await page.request.post('/api/v1/security/emergency-stop', { data: { reason: 'auditor tries', confirm: true }, headers })).status()).toBe(403)
 await page.getByRole('button', { name: 'Sign out' }).click()
 // Administrator: emergency stop with confirmation, then explicit recovery.
 await login(page, 'admin_ada')
 await page.getByRole('button', { name: 'Activate emergency stop' }).click()
 await page.getByLabel('Reason (recorded in the audit chain)').fill('browser incident drill')
 await expect(page.getByRole('button', { name: 'Confirm' })).toBeDisabled()
 await page.getByLabel('I confirm this action').check()
 await page.getByRole('button', { name: 'Confirm' }).click()
 await expect(page.getByText(/ACTIVE since .* by admin_ada: browser incident drill/)).toBeVisible()
 expect((await (await page.request.get('/api/v1/security/status')).json()).emergency_stop.active).toBe(true)
 await page.getByRole('button', { name: 'Recover from emergency stop' }).click()
 await page.getByLabel('Reason (recorded in the audit chain)').fill('drill complete')
 await page.getByLabel('I confirm this action').check()
 await page.getByLabel(/to confirm/).fill('RESUME PROTECTED OPERATIONS')
 await page.getByRole('button', { name: 'Confirm' }).click()
 await expect(page.getByText('Not active. New protected operations follow normal authorization.')).toBeVisible()
 const events = await (await page.request.get('/api/v1/security/events')).json()
 expect(events.map((e: { event_type: string }) => e.event_type)).toEqual(expect.arrayContaining(['EMERGENCY_STOP_ACTIVATED', 'EMERGENCY_STOP_RECOVERED']))
 await page.goto('/system/services')
 await expect(page.getByRole('cell', { name: 'control' })).toBeVisible()
 expect(errors).toEqual([])
})
