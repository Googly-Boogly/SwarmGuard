import { expect, test, type Page } from '@playwright/test'
async function login(page:Page) {
 await page.goto('/research/adversarial')
 await page.getByRole('button',{name:'Operator login'}).click()
 await page.getByLabel('Operator password').fill('browser-test-operator-password')
 await page.getByRole('button',{name:'Sign in as operator'}).click()
 await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible()
}
test('adaptive research, exact evidence, failure analysis and benchmark records',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/research/adversarial')
 await expect(page.getByRole('button',{name:'START RESEARCH RUN'})).toBeDisabled()
 expect((await page.request.post('/api/research/adversarial/runs',{data:{}})).status()).toBe(401)
 await login(page)
 await page.getByLabel('Scenario category').selectOption('distributed_coordination')
 await page.getByLabel('Maximum research iterations').fill('2')
 await page.getByRole('button',{name:'START RESEARCH RUN'}).click()
 await expect(page.getByText('COMPLETED',{exact:true})).toBeVisible({timeout:20000})
 const runs=await (await page.request.get('/api/research/adversarial')).json()
 const rid=runs[0].run_id
 const candidates=await (await page.request.get(`/api/research/runs/${rid}/candidates`)).json()
 expect(candidates).toHaveLength(2)
 expect(candidates[0].events.length).toBeGreaterThan(0)
 await expect(page.getByRole('heading',{name:'Candidate variations'})).toBeVisible()
 await page.getByRole('button',{name:'Inspect candidate'}).first().click()
 await expect(page.getByRole('dialog')).toContainText('Exact monitor observations and assessments')
 await expect(page.locator('.react-flow__node').first()).toBeVisible()
 await page.getByRole('button',{name:'Close dialog'}).click()
 await page.getByRole('link',{name:'Failure Analysis',exact:true}).click()
 await page.getByRole('button',{name:'Inspect failure'}).first().click()
 await expect(page.getByRole('heading',{name:'Verified facts',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Trusted ground truth',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Safety Benchmarks',exact:true}).click()
 await page.getByLabel('Maximum research iterations').fill('1')
 await page.getByRole('button',{name:'START BENCHMARK'}).click()
 await expect(page.getByText('COMPLETED',{exact:true})).toBeVisible({timeout:20000})
 const benchmarks=await (await page.request.get('/api/research/benchmarks')).json()
 const benchmark=await (await page.request.get(`/api/research/runs/${benchmarks[0].run_id}`)).json()
 expect(benchmark.executed).toBe(1)
 await expect(page.getByText('GLOBAL_MONITOR',{exact:true}).last()).toBeVisible()
 expect(errors).toEqual([])
})

test('legitimate research collaboration stays safe and scaling records are measured',async({page})=>{
 await login(page)
 await page.getByLabel('Scenario category').selectOption('legitimate_collaboration')
 await page.getByLabel('Maximum research iterations').fill('1')
 await page.getByRole('button',{name:'START RESEARCH RUN'}).click()
 await expect(page.getByText('COMPLETED',{exact:true})).toBeVisible({timeout:20000})
 const runs=await (await page.request.get('/api/research/adversarial')).json()
 const [candidate]=await (await page.request.get(`/api/research/runs/${runs[0].run_id}/candidates`)).json()
 expect(candidate.predictions.GLOBAL_MONITOR).toBe(false)
 expect(candidate.feedback.prohibited_outcome_occurred).toBe(false)
 expect(candidate.feedback.legitimate_objective_completed).toBe(true)
 await page.getByRole('link',{name:'Scaling Experiments',exact:true}).click()
 await page.getByRole('button',{name:'START SCALING RUN'}).click()
 await expect(page.getByText('COMPLETED',{exact:true})).toBeVisible({timeout:20000})
 const scaling=await (await page.request.get('/api/research/scaling')).json()
 const rows=await (await page.request.get(`/api/research/runs/${scaling[0].run_id}/candidates`)).json()
 expect(rows.map((r:{scaling:{agent_count:number}})=>r.scaling.agent_count)).toEqual([3,5,8,12])
 expect(rows.every((r:{scaling:{execution_ms:number}})=>r.scaling.execution_ms>0)).toBe(true)
})
