import { expect, test } from '@playwright/test'

test.skip(process.env.SWARMGUARD_E2E_LOCAL_ACCESS !== '1', 'Requires the isolated password-free local server')

test('local console runs two trials without any login UI or credentials', async ({ page }) => {
 await page.goto('/research/experiments/new')
 await expect(page.getByRole('combobox', { name: 'Dataset', exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: /Operator login|Sign in|Sign out/ })).toHaveCount(0)
 await expect(page.locator('input[type="password"]')).toHaveCount(0)
 const session = await (await page.request.get('/api/session')).json()
 expect(session.authenticated).toBe(true)
 expect(session.login_required).toBe(false)
 expect(session.roles).toEqual(['OPERATOR', 'RESEARCHER'])
 await page.getByRole('combobox', { name: 'Dataset', exact: true }).selectOption('swarmguard_autonomous')
 await page.getByRole('combobox', { name: 'Execution mode', exact: true }).selectOption('MOCK_AUTONOMOUS')
 await expect(page.getByText('2 total trials planned (maximum 2).', { exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'RUN EVALUATION', exact: true }).click()
 await expect(page.getByRole('heading', { name: /experiment_.*COMPLETED/ })).toBeVisible({ timeout: 30000 })
 const catalog = await (await page.request.get('/api/research/lab/catalog')).json()
 const record = await (await page.request.get(`/api/research/lab/experiments/${catalog.experiments[0].experiment_id}`)).json()
 expect(record.rows).toHaveLength(2)
 expect(record.validation.valid).toBe(true)
 await expect(page.getByRole('table', { name: 'Monitor comparison' }).getByRole('row')).toHaveCount(3)
 await expect(page.getByRole('table', { name: 'Trial outcomes' }).getByRole('row')).toHaveCount(3)
 await expect(page.locator('pre.json')).toHaveCount(0)
 await page.getByRole('button', { name: 'GENERATE REPORT', exact: true }).click()
 const report = page.getByLabel('Generated research report')
 await expect(report).toContainText('2 recorded / 2 planned')
 expect((await report.innerText()).length).toBeLessThan(5000)
 await expect(report).not.toContainText('SPECIALIZED_ETHICS_COUNCIL')
 await page.reload()
 await expect(page.getByRole('button', { name: 'RUN EVALUATION', exact: true })).toBeEnabled()
 await expect(page.getByRole('button', { name: /Operator login|Sign in|Sign out/ })).toHaveCount(0)
 const browserStorage = await page.evaluate(() => JSON.stringify(localStorage))
 expect(browserStorage).not.toContain(session.csrf_token)
})
