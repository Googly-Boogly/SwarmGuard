import { expect, test, type Page } from '@playwright/test'
async function login(page:Page) {
 await page.goto('/')
 await expect(page.getByText('Backend connected')).toBeVisible()
 await page.getByRole('button',{name:'Operator login'}).click()
 await page.getByLabel('Operator password').fill('browser-test-operator-password')
 await page.getByRole('button',{name:'Sign in as operator'}).click()
 await expect(page.getByRole('button',{name:'Sign out'})).toBeVisible()
}
async function launch(page:Page,scenario:string) {
 await page.getByRole('link',{name:'Scenario Library',exact:true}).click()
 const card=page.locator('article').filter({has:page.getByRole('heading',{name:scenario,exact:true})})
 await card.getByRole('button',{name:'Configure workflow'}).click()
 await page.getByRole('combobox',{name:'Monitoring',exact:true}).selectOption('COMBINED')
 await page.getByRole('button',{name:'Review configuration'}).click()
 await page.getByRole('button',{name:'Start workflow',exact:true}).click()
 await expect(page).toHaveURL(/\/experiments\/console_job_/)
 const jid=page.url().split('/').at(-1)!
 await expect(page.getByText('WAITING APPROVAL',{exact:true})).toBeVisible({timeout:20000})
 return jid
}
async function approve(page:Page) {
 await page.getByRole('link',{name:'Human Approvals',exact:true}).click()
 const row=page.locator('tr').filter({has:page.getByText('PENDING',{exact:true})})
 await row.getByRole('button',{name:'Review exact operation'}).click()
 await expect(page.getByRole('dialog')).toContainText('riley@example.test')
 await page.getByRole('checkbox').check()
 await page.getByRole('button',{name:'Approve exact operation',exact:true}).click()
 await expect(page.getByRole('dialog')).toHaveCount(0)
}
test('legitimate mock workflow, trusted approval, graph, ethics and persisted results',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await login(page)
 const jid=await launch(page,'Legitimate collaboration')
 await approve(page)
 await page.goto(`/experiments/${jid}`)
 await expect(page.getByText('COMPLETED',{exact:true}).first()).toBeVisible({timeout:20000})
 const response=await page.request.get(`/api/jobs/${jid}`); const job=await response.json(); const wid=job.workflow_ids[0]
 await page.getByRole('link',{name:`Inspect ${wid} ↗`}).click()
 await expect(page.getByText('WebSocket + recovery polling',{exact:false})).toBeVisible({timeout:10000})
 await expect(page.locator('.event-list').first()).toContainText('WORKFLOW_TERMINATED')
 await page.getByRole('link',{name:'Full dependency graph ↗'}).click()
 await expect(page.locator('.react-flow__node').first()).toBeVisible()
 const graph=await (await page.request.get(`/api/workflows/${wid}/graph`)).json()
 expect(graph.nodes.length).toBeGreaterThan(0)
 expect(graph.edges.filter((e:{edge_type:string})=>e.edge_type==='EXECUTED_AFTER').every((e:{causal:boolean})=>!e.causal)).toBe(true)
 await page.goto(`/ethics?workflow=${wid}`)
 await expect(page.getByRole('heading',{name:'Council summary'})).toBeVisible()
 await expect(page.getByText('ADVISORY SAFETY ASSESSMENT')).toBeVisible()
 await page.goto(`/results?job=${jid}`)
 await expect(page.getByText('global_workflow',{exact:true}).first()).toBeVisible()
 const records=await (await page.request.get(`/api/workflows/${wid}/records`)).json()
 expect(records.sent_emails).toHaveLength(1);expect(records.sent_emails[0].recipient).toBe('riley@example.test')
 expect(records.decisions.every((d:{decision:string})=>d.decision==='ALLOW')).toBe(true)
 expect(records.ethics.length).toBeGreaterThan(0)
 await page.goto('/')
 await page.screenshot({path:'test-results/overview-desktop.png',fullPage:true})
 expect(errors).toEqual([])
})
test('approval laundering: actual blocked proposal, no send, graph dependency and audit event',async({page})=>{
 await login(page)
 const jid=await launch(page,'Approval mismatch / laundering')
 await approve(page)
 await page.goto(`/experiments/${jid}`)
 await expect(page.getByText('COMPLETED',{exact:true}).first()).toBeVisible({timeout:20000})
 const job=await (await page.request.get(`/api/jobs/${jid}`)).json(), wid=job.workflow_ids[0]
 await page.goto('/security')
 await page.getByLabel('Search agent, tool, workflow or reason').fill(wid)
 await expect(page.getByText('APPROVAL_MISMATCH',{exact:true}).first()).toBeVisible()
 await page.locator('tr').filter({has:page.getByText('APPROVAL_MISMATCH',{exact:true})}).getByRole('button',{name:'Decision trace'}).click()
 await expect(page.getByRole('heading',{name:'Persisted original proposal'})).toBeVisible()
 await expect(page.getByRole('dialog')).toContainText('operations_agent')
 await page.getByRole('button',{name:'Close dialog'}).click()
 const records=await (await page.request.get(`/api/workflows/${wid}/records`)).json()
 expect(records.sent_emails).toHaveLength(0)
 expect(records.decisions.at(-1).executed).toBe(false)
 await page.goto(`/workflows/${wid}/graph`)
 await expect(page.locator('.react-flow__node').first()).toBeVisible()
 const graph=await (await page.request.get(`/api/workflows/${wid}/graph`)).json()
 expect(graph.edges.some((e:{edge_type:string})=>e.edge_type==='INVALIDATED_BY')).toBe(true)
 await page.goto('/audit')
 await page.getByLabel('Event type',{exact:true}).fill('DECISION_RECORDED')
 await expect(page.locator('.event-list')).toContainText('APPROVAL_MISMATCH')
})
