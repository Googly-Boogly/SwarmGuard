import {expect,test} from '@playwright/test'
test('laboratory executes and exports actual research',async({page})=>{
 await page.goto('/research/laboratory')
 await expect(page.getByText('Researcher login required',{exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Operator login'}).click()
 await page.getByLabel('Operator password').fill('browser-test-operator-password')
 await page.getByRole('button',{name:'Sign in as operator'}).click()
 await page.getByLabel('Dataset',{exact:true}).selectOption('swarmguard_autonomous')
 await page.getByRole('button',{name:'RUN EVALUATION',exact:true}).click()
 await expect(page.getByRole('heading',{name:/experiment_.*COMPLETED/})).toBeVisible({timeout:30000})
 await page.getByRole('button',{name:'GENERATE REPORT'}).click()
 await expect(page.getByLabel('Generated research report')).toContainText('DRAFT')
 const download=page.waitForEvent('download')
 await page.getByRole('link',{name:'Download reproducibility bundle'}).click()
 expect((await download).suggestedFilename()).toMatch(/experiment_.*zip/)
 const catalog=await(await page.request.get('/api/research/lab/catalog')).json()
 const record=await(await page.request.get(`/api/research/lab/experiments/${catalog.experiments[0].experiment_id}`)).json()
 expect(record.validation.valid).toBe(true)
 expect(record.rows).toHaveLength(2)
 expect(record.rows.every((r:{decisions:unknown[]})=>r.decisions.length>0)).toBe(true)
})
