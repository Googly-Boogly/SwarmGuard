import { expect, test, type Page } from '@playwright/test'

// Real FastAPI backend + Vite frontend; nothing is mocked. Run with SWARMGUARD_E2E_LOCAL_ACCESS=1.
test.skip(process.env.SWARMGUARD_E2E_LOCAL_ACCESS !== '1', 'Requires the isolated password-free local server')
test.setTimeout(180000)

const shots = process.env.SWARMGUARD_E2E_SHOTS
async function shot(page: Page, name: string) { if (shots) await page.screenshot({ path: `${shots}/${name}.png`, fullPage: true }) }

test('complete RQ1 pilot through the research laboratory', async ({ page, context }) => {
 await context.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://localhost:5173' })
 // 1–4. Laboratory → RQ1 → configure a small pilot with Local and Global monitors in Scripted mode.
 await page.goto('/research/laboratory')
 await expect(page.getByRole('heading', { name: 'RQ1 — Distributed Approval Laundering' })).toBeVisible()
 await page.getByRole('link', { name: 'NEW EXPERIMENT' }).first().click()
 await expect(page).toHaveURL(/\/research\/rq1\/new$/)
 await expect(page.getByRole('button', { name: /RUN EXPERIMENT \d{3}/ })).toBeDisabled()
 await page.getByRole('button', { name: /Use pilot settings/ }).click()
 await expect(page.getByRole('combobox', { name: 'Dataset' })).toHaveValue('development')
 await expect(page.getByLabel('A · Local Monitor (local_action)')).toBeChecked()
 await expect(page.getByLabel('B · Global Monitor (global_workflow)')).toBeChecked()
 await expect(page.getByRole('radio', { name: /Scripted/ })).toBeChecked()
 // LLM arm: live is unavailable on the offline test server (and says why); mock exercises the LLM pipeline.
 const llmMode = page.getByRole('combobox', { name: 'LLM mode' })
 await expect(llmMode.locator('option[value="live"]')).toBeDisabled()
 await expect(page.getByRole('note')).toContainText('SWARMGUARD_CONSOLE_LIVE_LLM=1')
 await llmMode.selectOption('mock')
 await expect(page.getByLabel('D · LLM Global monitor (llm_global)')).toBeChecked()
 await shot(page, '01-configure')
 // 5. Validate methodology.
 await page.getByRole('button', { name: 'VALIDATE METHODOLOGY' }).click()
 const report = page.getByLabel('Validation report')
 await expect(report).toContainText('WARNINGS', { timeout: 30000 })
 await expect(report).toContainText('Ground-truth labels are excluded from monitor observations')
 await expect(report).toContainText('Future events are excluded')
 await expect(report).toContainText('LLM inputs exclude labels and future events')
 // Changing a setting invalidates the validation.
 await page.getByRole('spinbutton', { name: 'Random seed' }).fill('3')
 await expect(page.getByRole('button', { name: 'RUN RQ1 EXPERIMENT' })).toBeDisabled()
 await page.getByRole('spinbutton', { name: 'Random seed' }).fill('0')
 await page.getByRole('button', { name: 'VALIDATE METHODOLOGY' }).click()
 await expect(report).toContainText('WARNINGS', { timeout: 30000 })
 await shot(page, '02-validated')
 // 6–7. Run and observe progress.
 await page.getByRole('button', { name: 'RUN RQ1 EXPERIMENT' }).click()
 await expect(page).toHaveURL(/\/research\/rq1\/experiments\/rq1_experiment_\d+/)
 const eid = page.url().split('/').pop()!.split('?')[0]
 await expect(page.getByRole('progressbar', { name: 'Workflows evaluated' })).toBeVisible()
 await expect(page.getByRole('tab', { name: 'Overview' })).toBeEnabled({ timeout: 90000 })
 await expect(page.getByRole('tab', { name: 'Overview' })).toHaveAttribute('aria-selected', 'true')  // results open automatically
 await page.getByRole('tab', { name: 'Live Monitor' }).click()
 await expect(page.getByText('Scenarios completed')).toBeVisible()
 await expect(page.locator('.rq1-stream li').first()).toBeVisible()
 await shot(page, '03-live')
 // 8. Results dashboard and metric verification against the backend record.
 await page.getByRole('tab', { name: 'Overview' }).click()
 const results = await (await page.request.get(`/api/research/rq1/experiments/${eid}/results`)).json()
 const pct = (v: number | null) => v === null ? 'Undefined' : `${(v * 100).toFixed(1)}%`
 for (const [title, value] of [['Local recall', results.analysis.primary.local_action.recall], ['Global recall', results.analysis.primary.global_workflow.recall], ['Local false-positive rate', results.analysis.primary.local_action.false_positive_rate], ['Global false-positive rate', results.analysis.primary.global_workflow.false_positive_rate]] as const)
  await expect(page.locator('.metric-card', { hasText: title }).first()).toContainText(pct(value))
 await expect(page.locator('.metric-card', { hasText: 'LLM Global recall' })).toContainText(pct(results.llm_analysis.primary.llm_global.recall))
 await expect(page.getByText(/SYNTHETIC MOCK \(not evidence\)/)).toBeVisible()
 expect(results.llm_usage.attempts).toBeGreaterThan(0)
 // A development pilot is not a registered procedure: the server computes no verdict, and the UI says so.
 const verdicts = await (await page.request.get(`/api/research/rq1/experiments/${eid}/hypotheses`)).json()
 expect(verdicts.verdicts).toEqual([])
 await expect(page.getByText(/No registered hypothesis covers this dataset partition/)).toBeVisible()
 await shot(page, '04-overview')
 await page.getByRole('tab', { name: 'Scientific Metrics' }).click()
 await expect(page.getByLabel('Local confusion matrix', { exact: true })).toContainText(`${results.analysis.primary.local_action.tp}TP`)
 await expect(page.getByLabel('Global confusion matrix', { exact: true })).toContainText(`${results.analysis.primary.global_workflow.fn}FN`)
 await expect(page.getByRole('table', { name: 'Metric comparison', exact: true })).toContainText('F1 score')
 await expect(page.getByLabel('Detection metrics chart').locator('.recharts-bar-rectangle').first()).toBeVisible()
 await expect(page.getByRole('table', { name: 'LLM metric comparison' })).toContainText('Unknown workflow predictions')
 await shot(page, '05-metrics')
 // 9–12. Raw data: filter by monitor, inspect a prediction, its monitor input and ground truth.
 await page.getByRole('tab', { name: 'Raw Data' }).click()
 const table = page.getByRole('table', { name: 'Raw data table' })
 await expect(table).toBeVisible()
 await page.getByRole('combobox', { name: 'Filter Monitor' }).selectOption('Local')
 await expect(page.getByRole('status').filter({ hasText: 'matching rows' })).toContainText(`${(await (await page.request.get(`/api/research/rq1/experiments/${eid}/raw?monitor=Local&page_size=5`)).json()).total} matching rows`)
 await expect(table.locator('tbody tr').first()).toContainText('Local')
 await page.getByRole('combobox', { name: 'Filter Monitor' }).selectOption('Global')
 await expect(table.locator('tbody tr').first()).toContainText('Global')
 await table.getByRole('button', { name: 'Step' }).click()
 await table.getByRole('button', { name: 'Expand row' }).first().click()
 await expect(page.locator('.rq1-expanded')).toContainText('recommendation')
 await shot(page, '06-raw')
 await page.getByRole('button', { name: 'Global missed unsafe workflows' }).click()
 await expect(page.getByRole('combobox', { name: 'Level' })).toHaveValue('workflow')
 await page.getByRole('combobox', { name: 'Filter Monitor' }).selectOption('')
 await page.getByRole('combobox', { name: 'Filter Prediction' }).selectOption('')
 await table.getByRole('button', { name: 'Open record' }).first().click()
 const panel = page.getByRole('dialog', { name: 'Raw data record' })
 await expect(panel.getByRole('heading', { name: /C · Monitor input/ })).toBeVisible()
 await expect(panel.getByRole('heading', { name: 'B · Ground truth' })).toBeVisible()
 await expect(panel).toContainText('Labels were joined after predictions were fixed')
 await panel.getByRole('button', { name: 'VIEW ORIGINAL JSON' }).click()
 await expect(panel.getByLabel('Original JSON')).toContainText('"snapshot_digest"')
 await shot(page, '07-record')
 await panel.getByRole('button', { name: 'LLM monitor' }).click()
 await expect(panel.getByRole('heading', { name: 'C2 · Exact LLM request' })).toBeVisible()
 await panel.getByRole('button', { name: 'VIEW EXACT USER MESSAGE' }).click()
 await expect(panel.getByLabel('Original JSON')).toContainText('"untrusted_workflow_data"')
 await shot(page, '07b-llm-record')
 await panel.getByRole('button', { name: 'Close record' }).click()
 await page.getByRole('combobox', { name: 'Level' }).selectOption('checkpoint')
 await page.getByRole('combobox', { name: 'Filter Monitor' }).selectOption('LLM Global')
 await expect(table.locator('tbody tr').first()).toContainText('LLM Global')
 // 13–14. Monitor comparison side by side.
 await page.getByRole('tab', { name: 'Monitor Comparisons' }).click()
 await page.getByRole('combobox', { name: 'Select workflow' }).selectOption('wf_001')
 await expect(page.getByLabel('local monitor', { exact: true })).toContainText('Observation scope')
 await expect(page.getByLabel('global monitor', { exact: true })).toContainText('Observation scope')
 await expect(page.getByText('Extra information only in the Global observation')).toBeVisible()
 await shot(page, '08-comparison')
 // 15–16. Scenario and workflow graph.
 await page.getByRole('tab', { name: 'Scenarios' }).click()
 await page.getByRole('table', { name: 'Scenarios' }).getByRole('button', { name: 'Inspect' }).first().click()
 await expect(page.getByRole('heading', { name: 'Global safety constraint (ground truth)' })).toBeVisible()
 await page.getByRole('button', { name: 'Workflow graph' }).click()
 await expect(page.getByLabel('Workflow dependency graph').locator('.react-flow__node').first()).toBeVisible()
 await page.getByLabel('Workflow dependency graph').locator('.react-flow__node[data-id^="action:"]').nth(2).click()
 await expect(page.getByText('Related events')).toBeVisible()
 await shot(page, '09-workflow')
 // 17. Failure analysis.
 await page.getByRole('tab', { name: 'Failure Analysis' }).click()
 await expect(page.getByRole('group', { name: 'Failure categories' })).toContainText('Local missed, Global detected')
 await shot(page, '10-failures')
 // 18–19. Findings and copy.
 await page.getByRole('tab', { name: 'Research Findings' }).click()
 await expect(page.getByText('orientation only')).toBeVisible()
 await page.getByTestId('copy-summary').click()
 await expect(page.getByText('Copied to clipboard').first()).toBeVisible()
 const findings = await (await page.request.get(`/api/research/rq1/experiments/${eid}/findings`)).json()
 expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(findings.copy.results_summary)
 await shot(page, '11-findings')
 await page.getByRole('tab', { name: 'Experiment Details' }).click()
 await expect(page.getByText('Research methodology')).toBeVisible()
 // 20. Refresh: the experiment remains available.
 await page.reload()
 await expect(page.getByRole('heading', { name: eid })).toBeVisible()
 await page.goto('/research/rq1')
 await expect(page.getByRole('link', { name: eid })).toBeVisible()
})

test('selects and validates the frozen 60-workflow follow-up without consuming final predictions', async ({ page }) => {
 await page.goto('/research/rq1/new')
 await expect(page.getByRole('combobox', { name: 'Dataset' })).toHaveValue('rq1_robustness_60')
 await expect(page.getByText(/60 total workflow trials · 12 unsafe · 48 legitimate/)).toBeVisible()
 await expect(page.getByRole('combobox', { name: 'LLM mode' })).toHaveValue('none')
 await expect(page.getByRole('combobox', { name: 'LLM mode' })).toBeDisabled()
 await expect(page.getByRole('spinbutton', { name: 'Number of trials' })).toHaveValue('1')
 await expect(page.getByRole('spinbutton', { name: 'Number of trials' })).toBeDisabled()
 const response = page.waitForResponse(r => r.url().endsWith('/api/research/rq1/validate') && r.request().method() === 'POST')
 await page.getByRole('button', { name: 'VALIDATE METHODOLOGY' }).click()
 const validation = await (await response).json()
 expect(validation.status).not.toBe('INVALID')
 expect([validation.selected_scenarios, validation.legitimate, validation.unsafe]).toEqual([60, 48, 12])
 expect(validation.checks.filter((c: { status: string }) => c.status === 'FAIL')).toHaveLength(0)
 await expect(page.getByRole('button', { name: /RUN EXPERIMENT \d{3}/ })).toBeEnabled()
 // Do not click: the final dataset is never repeatedly evaluated for frontend debugging.
})
