"""Disposable hardened-deployment verification (Docker Compose). Never point this at production.

Generates fresh local secrets, builds and starts the stack, verifies hardening, network isolation from
*inside* containers, authentication, authorization, approval flow, audit persistence/verification, frontend
connectivity and fail-closed behaviour, then tears everything down (``--keep`` to leave it running).
"""
from __future__ import annotations
import argparse
import json
import os
import secrets
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
COMPOSE_FILE = ROOT / "deployment" / "compose" / "compose.hardened.yml"
SECRETS = ROOT / "deployment" / "secrets"
MARKER = SECRETS / ".generated-by-verify-deployment"
PROJECT = "swarmguard-stage7"
FRONTEND = "http://127.0.0.1:8080"
SERVICES = ("database", "executor", "gateway", "api", "frontend")
RESULTS: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str = "") -> bool:
    RESULTS.append((name, bool(ok), detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}{': ' + detail if detail else ''}", flush=True)
    return bool(ok)


def compose(*args: str, timeout: int = 900, check_rc: bool = True, input_text: str | None = None) -> subprocess.CompletedProcess:
    proc = subprocess.run(["docker", "compose", "-f", str(COMPOSE_FILE), "-p", PROJECT, *args], cwd=ROOT, text=True,
                          capture_output=True, timeout=timeout, input=input_text)
    if check_rc and proc.returncode:
        raise RuntimeError(f"docker compose {' '.join(args[:3])} failed:\n{proc.stdout[-2000:]}\n{proc.stderr[-2000:]}")
    return proc


def generate_secrets() -> dict[str, str]:
    if SECRETS.exists():
        if not MARKER.exists():
            raise SystemExit(f"{SECRETS} exists and was not generated by this script; refusing to touch it")
        shutil.rmtree(SECRETS)
    SECRETS.mkdir(mode=0o700, parents=True)
    subprocess.run([sys.executable, str(ROOT / "stage7_cli.py"), "init-secrets", "--dir", str(SECRETS)], check=True,
                   cwd=ROOT, capture_output=True)
    sys.path.insert(0, str(ROOT))
    from swarmguard.console.auth import password_hash
    passwords = {u: secrets.token_urlsafe(18) for u in ("operator_alice", "admin_ada", "auditor_aki")}
    roles = {"operator_alice": ["OPERATOR"], "admin_ada": ["ADMINISTRATOR"], "auditor_aki": ["AUDITOR"]}
    (SECRETS / "operators.json").write_text(json.dumps({"accounts": [
        {"username": u, "roles": roles[u], "password_hash": password_hash(p)} for u, p in passwords.items()]}))
    (SECRETS / "agent").mkdir(mode=0o700)
    subprocess.run([sys.executable, str(ROOT / "stage7_cli.py"), "issue-token", "--issuer-key",
                    str(SECRETS / "identity_issuer.key"), "--agent", "operations_agent", "--runtime", "runtime_alpha",
                    "--ttl-seconds", "7200", "--out", str(SECRETS / "agent" / "token")], check=True, cwd=ROOT,
                   capture_output=True)
    # Directory 0700 protects secrets from other host users; files are 0644 only so the non-root container
    # users (bind-mounted compose secrets) can read the ones mounted into them. The issuer private key is
    # never mounted into any container.
    for path in SECRETS.rglob("*"):
        if path.is_file():
            path.chmod(0o600 if path.name == "identity_issuer.key" else 0o644)
    MARKER.write_text("disposable\n")
    return passwords


def wait_healthy(timeout: int = 300) -> dict[str, str]:
    deadline = time.monotonic() + timeout
    states: dict[str, str] = {}
    while time.monotonic() < deadline:
        out = compose("ps", "--all", "--format", "json", check_rc=False).stdout
        rows = [json.loads(line) for line in out.splitlines() if line.strip().startswith("{")]
        states = {r["Service"]: (r.get("Health") or r.get("State")) for r in rows}
        if all(states.get(s) == "healthy" for s in SERVICES):
            return states
        if any(v in ("exited", "dead") for k, v in states.items() if k != "migrate") or \
                (states.get("migrate") == "exited" and "Exited (0)" not in json.dumps(rows)):
            break
        time.sleep(3)
    return states


def container_ids() -> dict[str, str]:
    out = compose("ps", "-q", "--all").stdout.split()
    ids = {}
    for cid in out:
        info = json.loads(subprocess.check_output(["docker", "inspect", cid]))[0]
        ids[info["Config"]["Labels"]["com.docker.compose.service"]] = cid
    return ids


def verify_hardening() -> None:
    for service, cid in container_ids().items():
        info = json.loads(subprocess.check_output(["docker", "inspect", cid]))[0]
        hc, cfg = info["HostConfig"], info["Config"]
        user = cfg.get("User") or "root"
        mounts = [m.get("Source", "") for m in info.get("Mounts", [])]
        ports = {k: v for k, v in (hc.get("PortBindings") or {}).items() if v}
        ok = (not hc.get("Privileged") and hc.get("NetworkMode") not in ("host",) and "ALL" in (hc.get("CapDrop") or [])
              and any("no-new-privileges" in o for o in hc.get("SecurityOpt") or []) and hc.get("ReadonlyRootfs")
              and not any("docker.sock" in m for m in mounts) and hc.get("Memory", 0) > 0 and hc.get("PidsLimit"))
        nonroot = service == "database" or user not in ("", "root", "0", "0:0")
        exposure = (service == "frontend" and all(b.get("HostIp") == "127.0.0.1" for v in ports.values() for b in v)) or \
            (service != "frontend" and not ports)
        check(f"hardening {service}", ok and nonroot and exposure,
              f"user={user} read_only={hc.get('ReadonlyRootfs')} cap_drop={hc.get('CapDrop')} "
              f"cap_add={hc.get('CapAdd') or []} ports={ {k: [b.get('HostIp') + ':' + b.get('HostPort') for b in v] for k, v in ports.items()} }")


PROBE = r"""
import json, socket, sys
out = {}
for name, host, port in [("gateway", "gateway", 8000), ("executor", "executor", 8000), ("database", "database", 5432),
                         ("api", "api", 8000), ("internet", "1.1.1.1", 443)]:
    try:
        socket.create_connection((host, port), timeout=3).close(); out[name] = "reachable"
    except OSError as exc:
        out[name] = "unreachable:" + type(exc).__name__
print(json.dumps(out))
"""


def probe_from(service: str) -> dict[str, str]:
    if service == "agent-runtime":
        proc = compose("--profile", "agent", "run", "--rm", "--no-deps", "-T", "agent-runtime", "python", "-c", PROBE,
                       check_rc=False)
    else:
        proc = compose("exec", "-T", service, "python", "-c", PROBE, check_rc=False)
    try:
        return json.loads(proc.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError):
        return {"error": (proc.stderr or proc.stdout)[-300:]}


def verify_network_isolation() -> None:
    agent = probe_from("agent-runtime")
    check("agent -> gateway reachable", agent.get("gateway") == "reachable", json.dumps(agent))
    for target in ("executor", "database", "api", "internet"):
        check(f"agent -> {target} blocked", str(agent.get(target, "")).startswith("unreachable"), agent.get(target, "?"))
    gateway = probe_from("gateway")
    check("gateway -> executor reachable (positive control)", gateway.get("executor") == "reachable", json.dumps(gateway))
    check("gateway -> internet blocked", str(gateway.get("internet", "")).startswith("unreachable"))
    executor = probe_from("executor")
    check("executor -> internet blocked", str(executor.get("internet", "")).startswith("unreachable"), json.dumps(executor))


def run_agent_scenario() -> dict[str, dict[str, Any]]:
    proc = subprocess.Popen(["docker", "compose", "-f", str(COMPOSE_FILE), "-p", PROJECT, "--profile", "agent", "run",
                             "--rm", "--no-deps", "-T", "agent-runtime"], cwd=ROOT, text=True, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE)
    steps: dict[str, dict[str, Any]] = {}
    assert proc.stdout is not None
    for line in proc.stdout:
        line = line.strip()
        if not line.startswith("{"):
            continue
        step = json.loads(line)
        steps[step["step"]] = step
        print("    agent>", line, flush=True)
        if step["step"] == "awaiting_human_approval" and step.get("approval_id"):
            approve = compose("exec", "-T", "api", "python", "stage7_cli.py", "approve", "--database",
                              "postgresql://sg_control@database:5432/swarmguard", "--approval-key",
                              "/run/secrets/approval_signing_key", "--approvers", "operator_alice", "--approval",
                              step["approval_id"], "--approver", "operator_alice", check_rc=False)
            print("    host > approval:", (approve.stdout.strip().splitlines() or [approve.stderr[-300:]])[-1], flush=True)
    proc.wait(timeout=120)
    return steps


AGENT_REQUEST = r"""
import json, os, httpx
token = open('/run/secrets/agent_token').read().strip()
headers = {} if os.environ.get('NO_TOKEN') else {'Authorization': 'Bearer ' + token}
r = httpx.post('http://gateway:8000/api/v1/capabilities/execute', headers=headers, timeout=20,
               json={'request_id': os.environ['RID'], 'workflow_id': 'wf_remote', 'tool': 'read_document', 'resource_id': 'doc_service_faq'})
print(json.dumps({'http': r.status_code, **{k: r.json().get(k) for k in ('decision', 'reason_code', 'executed')}}))
"""


def agent_request(rid: str, no_token: bool = False) -> dict[str, Any]:
    env = ["-e", f"RID={rid}"] + (["-e", "NO_TOKEN=1"] if no_token else [])
    proc = compose("--profile", "agent", "run", "--rm", "--no-deps", "-T", *env, "agent-runtime", "python", "-c",
                   AGENT_REQUEST, check_rc=False, timeout=120)
    try:
        return json.loads(proc.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError):
        return {"error": (proc.stderr or proc.stdout)[-300:]}


class Browser:
    """Minimal browser stand-in. Browsers send ``Secure`` cookies to http://localhost (a trustworthy origin);
    urllib's CookieJar does not, so the session cookie is carried explicitly."""

    def __init__(self) -> None:
        self.cookie = ""
        self.csrf = ""

    def call(self, method: str, path: str, body: Any = None) -> tuple[int, Any]:
        data = json.dumps(body).encode() if body is not None else None
        headers = {"Origin": "http://localhost:8080", "Content-Type": "application/json", "X-CSRF-Token": self.csrf,
                   "Host": "localhost:8080", **({"Cookie": self.cookie} if self.cookie else {})}
        req = urllib.request.Request(FRONTEND + path, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=10) as resp:
                for header in resp.headers.get_all("Set-Cookie") or []:
                    self.cookie = header.split(";", 1)[0]
                text = resp.read().decode()
                return resp.status, json.loads(text) if text.startswith(("{", "[")) else text
        except urllib.error.HTTPError as exc:
            return exc.code, exc.read().decode()[:300]

    def login(self, username: str, password: str) -> bool:
        status, body = self.call("POST", "/api/session", {"username": username, "password": password})
        self.csrf = body.get("csrf_token", "") if isinstance(body, dict) else ""
        return status == 200 and bool(self.cookie)


def verify_database_roles() -> None:
    snippet = r"""
import json, psycopg
pw = open('/run/secrets/db_gateway_password').read().strip()
with psycopg.connect('postgresql://sg_gateway@database:5432/swarmguard', password=pw, autocommit=True) as c:
    out = {}
    for name, sql in [('insert_sent_email', "INSERT INTO sent_emails(email_id, action_id, workflow_id, approval_id, resource_id, resource_version, recipient, subject, body, status, sent_at) VALUES ('x','x','x','x','x',1,'x','x','x','x','x')"),
                      ('update_events', "UPDATE events SET summary='x'"), ('delete_chain', 'DELETE FROM audit_chain'),
                      ('create_table', 'CREATE TABLE evil(x int)')]:
        try:
            c.execute(sql); out[name] = 'ALLOWED'
        except psycopg.errors.InsufficientPrivilege:
            out[name] = 'DENIED'
print(json.dumps(out))
"""
    proc = compose("exec", "-T", "gateway", "python", "-c", snippet, check_rc=False)
    try:
        result = json.loads(proc.stdout.strip().splitlines()[-1])
    except (IndexError, ValueError):
        result = {"error": proc.stderr[-300:]}
    check("gateway DB role cannot write outbox, rewrite audit or run DDL",
          result and all(v == "DENIED" for v in result.values()), json.dumps(result))


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--keep", action="store_true", help="leave the deployment running")
    args = p.parse_args()
    if shutil.which("docker") is None:
        print("Docker not available: deployment verification NOT RUN")
        return 2
    print("== generating disposable secrets"); passwords = generate_secrets()
    try:
        print("== building and starting hardened stack", flush=True)
        compose("--profile", "agent", "build", timeout=1800)
        compose("up", "-d", timeout=600, check_rc=False)
        states = wait_healthy()
        check("all services healthy", all(states.get(s) == "healthy" for s in SERVICES), json.dumps(states))
        migrate = compose("logs", "migrate", check_rc=False).stdout
        check("migrations applied by the migrate job", '"schema_migrations": [1, 2]' in migrate, migrate.strip().splitlines()[-1][-160:]
              if migrate.strip() else "no migrate output")
        print("== container hardening"); verify_hardening()
        print("== network isolation (tested from inside containers)"); verify_network_isolation()
        print("== database least privilege"); verify_database_roles()
        print("== readiness endpoints")
        for service in ("gateway", "executor"):
            out = compose("exec", "-T", service, "python", "-c", "import urllib.request;print(urllib.request.urlopen("
                          "'http://127.0.0.1:8000/health/ready',timeout=3).read().decode())", check_rc=False).stdout
            check(f"{service} ready", '"status":"ready"' in out.replace(" ", ""), out.strip()[-160:])
        print("== authentication")
        check("request without credential rejected", agent_request("no_token", no_token=True).get("http") == 401)
        print("== untrusted agent scenario (approval by trusted host)"); s = run_agent_scenario()
        check("authorized mock execution", s.get("send_with_approval", {}).get("executed") is True)
        check("missing approval not executed", s.get("send_without_approval", {}).get("executed") is False,
              str(s.get("send_without_approval", {}).get("reason_code")))
        check("forged approval blocked", s.get("send_with_forged_approval", {}).get("decision") == "BLOCK")
        check("approval replay blocked", s.get("approval_replay_new_request", {}).get("reason_code") == "APPROVAL_ALREADY_USED")
        check("identity spoof in body rejected", s.get("identity_spoof_in_body", {}).get("http") == 422)
        direct = s.get("direct_executor_access", {})
        check("agent -> executor direct access impossible", direct.get("reachable") is False, json.dumps(direct))
        env_report = s.get("agent_environment", {})
        # GPG_KEY is the public Python release-signing key fingerprint inherited from the base image.
        flagged = [v for v in env_report.get("secret_like_variables", []) if v != "GPG_KEY"]
        check("agent container holds only its own credential",
              env_report.get("files_in_run_secrets") == ["agent_token"] and flagged == [], json.dumps(env_report))
        print("== frontend and control API through the reverse proxy")
        browser = Browser()
        status, html = browser.call("GET", "/")
        check("frontend serves the console", status == 200 and "<div id=\"root\"" in str(html))
        status, health = browser.call("GET", "/api/health")
        check("frontend -> api proxy works", status == 200, str(health)[:120])
        check("auditor login", browser.login("auditor_aki", passwords["auditor_aki"]))
        status, report = browser.call("GET", "/api/v1/audit/verification")
        report = report if isinstance(report, dict) else {"raw": str(report)[:300]}
        check("audit events persisted and chain verifies", status == 200 and report.get("status") == "PASS"
              and report.get("chained_events", 0) > 0, f"HTTP {status} {report.get('status')} "
              f"{report.get('chained_events')} events {report.get('raw', '')}")
        status, sec = browser.call("GET", "/api/v1/security/status")
        sent = sec.get("protected_executions", {}).get("simulated_emails_sent") if isinstance(sec, dict) else None
        check("frontend status reflects backend records", status == 200 and sent == 1, f"simulated_emails_sent={sent}")
        status, _ = browser.call("POST", "/api/v1/security/emergency-stop", {"reason": "not allowed", "confirm": True})
        check("auditor cannot activate emergency stop", status == 403, f"HTTP {status}")
        status, _ = browser.call("POST", "/api/workflows", {"scenario_ids": ["legitimate_collaboration"]})
        check("in-process execution disabled in control service", status == 403, f"HTTP {status}")
        admin = Browser()
        check("administrator login", admin.login("admin_ada", passwords["admin_ada"]))
        status, stop = admin.call("POST", "/api/v1/security/emergency-stop", {"reason": "deployment drill", "confirm": True})
        check("administrator activates emergency stop", status == 200 and stop.get("active") is True)
        stopped = agent_request("during_stop")
        check("emergency stop blocks new operations", stopped.get("reason_code") == "EMERGENCY_STOP_ACTIVE"
              and stopped.get("executed") is False, json.dumps(stopped))
        status, _ = admin.call("POST", "/api/v1/security/emergency-stop/recover",
                               {"reason": "drill over", "confirmation_phrase": "RESUME PROTECTED OPERATIONS"})
        check("explicit recovery", status == 200 and agent_request("after_stop").get("executed") is True)
        print("== failure injection")
        compose("stop", "executor", check_rc=False)
        down = agent_request("executor_down")
        check("executor down -> fail closed", down.get("reason_code") == "EXECUTOR_UNAVAILABLE" and down.get("executed") is False,
              json.dumps(down))
        compose("stop", "database", check_rc=False)
        nodb = agent_request("database_down")
        check("database down -> fail closed", nodb.get("http") == 503 and nodb.get("executed") is False, json.dumps(nodb))
        if args.keep:   # leave a usable stack behind: restore the services stopped by fault injection
            compose("start", "database", "executor", check_rc=False)
            compose("restart", "gateway", "api", check_rc=False)
            states = wait_healthy()
            check("stack restored after fault injection (--keep)", all(states.get(s) == "healthy" for s in SERVICES),
                  json.dumps(states))
    except Exception as exc:  # noqa: BLE001 - report, never pass silently
        check("deployment verification completed", False, f"{type(exc).__name__}: {str(exc)[:600]}")
    finally:
        if not args.keep:
            compose("--profile", "agent", "down", "-v", "--remove-orphans", check_rc=False, timeout=300)
            shutil.rmtree(SECRETS, ignore_errors=True)
        else:
            # Host-only, 0600, git-ignored: the generated logins for manual testing of the kept stack.
            creds = SECRETS / "operator-passwords.txt"
            fd = os.open(creds, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
            with os.fdopen(fd, "w") as out:
                out.write("".join(f"{u}\t{pw}\n" for u, pw in passwords.items()))
            print(f"\nStack left running on {FRONTEND}. Logins (username, password): {creds}")
    ok = all(r[1] for r in RESULTS)
    print(f"\n{sum(r[1] for r in RESULTS)}/{len(RESULTS)} deployment checks passed")
    print(f"Deployment verification: {'PASS' if ok else 'FAIL'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
